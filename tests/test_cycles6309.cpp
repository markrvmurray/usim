//
// test_cycles6309.cpp
// Per-instruction cycle-timing test for the HD6309, in both MD modes.
//
// The aggregate gates (`make cycles`, `make cycles6309`) prove that a
// whole program's total has not moved. They cannot say which
// instruction moved it, and they barely exercise native mode at all.
// This test executes one instruction at a time and asserts its exact
// cost in emulation mode AND in native mode, so a single mistimed
// opcode or indexed postbyte is named rather than merely detected.
//
// The expected figures are NOT taken from this emulator. They come from
// Darren Atkinson's "6x09 Instruction Sets" (measured on real silicon),
// cross-checked opcode by opcode against Chet Simpson's HD6309
// Technical Reference Guide; where the two disagreed the raw text was
// read and the disagreement resolved in the comment above
// hd6309::native_delta. That makes this an independent check of the
// model rather than a snapshot of it.
//
// vim: ts=8 sw=8 noet:
//

#include <cstdio>
#include <cstdlib>
#include <cstring>

#include "hd6309.h"
#include "memory.h"

static constexpr Word CODE = 0x0400;

struct Case {
	const char	*bytes;		// instruction, as hex digits
	int		emul;		// cycles with MD bit 0 clear
	int		native;		// cycles with MD bit 0 set
	const char	*name;
};

// A CPU that stops after exactly one instruction and reports what that
// instruction cost. USim::tick() folds the previous instruction's count
// into total_cycles and zeroes `cycles` before this one runs, so at
// post_exec `cycles` is this instruction's charge and nothing else.
class Probe : public hd6309 {
public:
	uint32_t	cost = 0;

	void set_native(bool on)	{ md = on ? md_native : 0x00; }

	// Benign state: pointers into free RAM, non-zero divisors so
	// DIVD/DIVQ do not take the divide-by-zero trap, and a small W so
	// TFM terminates.
	void seed() {
		x = 0x0100; y = 0x0110; u = 0x0120; s = 0x0180;
		d = 0x0007; w = 0x0003; dp = 0x00;
	}
protected:
	void post_exec() override { cost = cycles; halt(); }
};

static int run_one(const char *hex, bool native)
{
	Probe cpu;
	auto ram = std::make_shared<RAM>(0x10000);
	cpu.attach(ram, 0x0000, 0x0000);

	// Uniform non-zero fill: a zero divisor would silently measure the
	// divide-by-zero trap instead of the instruction under test.
	for (unsigned a = 0; a < 0x10000; a++) {
		ram->write((Word)a, 0x01);
	}
	ram->write(0xfffe, CODE >> 8);
	ram->write(0xffff, CODE & 0xff);

	Word a = CODE;
	for (size_t i = 0; hex[i] && hex[i + 1]; i += 2) {
		char b[3] = { hex[i], hex[i + 1], 0 };
		ram->write(a++, (Byte)strtoul(b, nullptr, 16));
	}

	cpu.reset();
	cpu.set_native(native);
	cpu.seed();
	cpu.tick();
	return (int)cpu.cost;
}

